/**
 * The web app manifest and the offline service worker (#111). Pure: the
 * build writes both into dist. The worker is network-first for every
 * same-origin GET, so an online reader always gets the current build; what
 * it fetched is kept, and offline it answers from that copy. The homepage,
 * its scripts, styles and fonts are fetched at install, so search and the
 * shortlist work offline after one visit. The cache name carries the build
 * time, and older caches are deleted on activate.
 */

/**
 * manifest.webmanifest for the site. Relative URLs resolve against the
 * manifest, which sits at the site root, so the same file works on Pages
 * and on a local server.
 */
export function webManifest(site) {
  return {
    name: site.title,
    short_name: "Free Game Dev Assets",
    description: site.tagline,
    start_url: "./",
    scope: "./",
    display: "standalone",
    background_color: "#eef1f4",
    theme_color: "#1a4d3e",
    icons: [{ src: "favicon.svg", sizes: "any", type: "image/svg+xml", purpose: "any maskable" }],
  };
}

/** sw.js: `version` names the cache, `precache` lists site-relative files. */
export function serviceWorkerJs({ version, precache }) {
  return `// Generated by site/build.mjs (lib/offline.mjs). Network first; the cache is the offline copy.
const CACHE = ${JSON.stringify(`fgda-${version}`)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE.map((p) => new URL(p, self.registration.scope)))).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("fgda-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok && res.type === "basic") {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy));
        }
        return res;
      })
      .catch(async () => {
        const hit = await caches.match(req, { ignoreSearch: req.mode === "navigate" });
        if (hit) return hit;
        // An uncached page offline: the catalog home, which can still search.
        if (req.mode === "navigate") return caches.match(new URL("./", self.registration.scope));
        return Response.error();
      })
  );
});
`;
}
